"""Pick one clear reference photo per disease for the website ("Does your leaf look like this?").

    python -m crop_doctor.app.make_references

Only sources we may show publicly, with credit:
- potato: Tanzania Irish Potato dataset (real farm photos, CC-BY-4.0), training split only;
- tomato: PlantVillage (lab photos, Hughes & Salathe 2015), training split only.
Not used: PlantDoc (scraped from the web) and Tomato-Village (no licence).

From up to 80 random training photos per disease, keep those the final model is at least 95% sure about, then
pick the one whose symptoms are most VISIBLE to a person: the most damaged area (colour estimate) while the leaf
is still mostly alive (under 45% damaged). Healthy leaves: the least damaged. Small photos are skipped. Output: web/public/reference/<label>.jpg + web/lib/references.ts.
"""
from __future__ import annotations

import json

import numpy as np
import pandas as pd
import torch
from PIL import Image

from crop_doctor import config
from crop_doctor.model.backends import TorchBackend
from crop_doctor.model.crops import crop_of, mask_logits
from crop_doctor.uncertainty.calibration import softmax
from crop_doctor.vision_extras.severity import estimate

SPLITS = config.ROOT / "crop_doctor" / "data" / "splits_v2"
OUT = config.ROOT / "web" / "public" / "reference"
CREDIT = {
    "tanzania": "Tanzania Irish Potato dataset (Zenodo 8286529), CC BY 4.0",
    "plantvillage": "PlantVillage dataset (Hughes & Salathé, 2015)",
}
PER_CLASS = 80
# Chosen by eye from the top candidates: the automatic pick counted photo shadows as damage, or showed faint
# symptoms. These show the textbook signs (target spots with yellow halo; yellow patches of leaf mould).
OVERRIDES = {
    "tomato_early_blight": "plantvillage/raw/color/Tomato___Early_blight/3c5e2faa-3bca-4d88-8841-fa06cf7388f1___RS_Erly.B 9599.JPG",
    "tomato_leaf_mold": "plantvillage/raw/color/Tomato___Leaf_Mold/a95f0a82-5cad-423a-be56-8205317909e8___Crnl_L.Mold 8677.JPG",
}


def main() -> None:
    app = json.loads((config.OUTPUTS_DIR / "app_model.json").read_text())
    backend = TorchBackend(config.OUTPUTS_DIR / app["checkpoint"], dev=torch.device("cpu"))
    classes = json.loads((SPLITS / "classes.json").read_text())
    pool = pd.concat([
        pd.read_csv(SPLITS / "field_train.csv").query("source == 'tanzania'"),
        pd.read_csv(SPLITS / "lab_train.csv").query("source == 'plantvillage' and label.str.startswith('tomato')",
                                                    engine="python"),
    ])
    OUT.mkdir(parents=True, exist_ok=True)
    refs = {}
    for label in classes:
        cand = pool[pool["label"] == label]
        if cand.empty:
            print(f"  {label}: no licensed photos")
            continue
        if label in OVERRIDES:
            cand = cand[cand["path"] == OVERRIDES[label]]
        else:
            cand = cand.sample(min(PER_CLASS, len(cand)), random_state=0)
        healthy = label.endswith("_healthy")
        scored = []
        for path in cand["path"]:
            with Image.open(config.DATASETS_DIR / path) as im:
                if min(im.size) < 224:
                    continue
                lg = backend.raw_logits(im)
                frac = estimate(im.convert("RGB"))["fraction"]
            p = float(softmax(mask_logits(lg[None], classes, np.array([crop_of(label)])), 1.0)[0][classes.index(label)])
            if frac is None or p < 0.95 or (not healthy and frac > 0.45):
                continue
            scored.append((-frac if healthy else frac, p, path))
        if not scored:
            print(f"  {label}: no clear candidate")
            continue
        _, best_p, best = max(scored)
        row = cand[cand["path"] == best].iloc[0]
        img = Image.open(config.DATASETS_DIR / best).convert("RGB")
        side = min(img.size)                                   # centre square crop, 480 px
        left, top = (img.width - side) // 2, (img.height - side) // 2
        img.crop((left, top, left + side, top + side)).resize((480, 480), Image.LANCZOS).save(OUT / f"{label}.jpg", quality=85)
        refs[label] = {"src": f"/reference/{label}.jpg", "credit": CREDIT[row["source"]]}
        print(f"  {label}: {row['source']}  p={best_p:.3f}  damage={max(scored)[0]:+.2f}  ({len(scored)} candidates)")
    body = ",\n".join(f'  {k}: {{ src: "{v["src"]}", credit: "{v["credit"]}" }}' for k, v in refs.items())
    (config.ROOT / "web" / "lib" / "references.ts").write_text(
        "// One reference photo per disease. GENERATED by `python -m crop_doctor.app.make_references`.\n"
        "// Only publicly licensed sources (see that script). Don't edit by hand.\n"
        f"export const REFERENCES: Record<string, {{ src: string; credit: string }}> = {{\n{body},\n}};\n",
        encoding="utf-8")
    print(f"wrote {len(refs)} reference photos to {OUT}")


if __name__ == "__main__":
    main()
